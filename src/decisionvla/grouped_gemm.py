"""Explicit grouped-linear backend selection, preserving adapter parameter names."""
import torch
from torch.autograd.function import once_differentiable

EXPERT_KERNELS = ("torch_grouped_mm", "triton_sm120", "triton_sm120_lora", "triton_sm120_backward",
                  "cublas_sm120_forward")


def check_expert_kernel(kernel, device):
    if kernel not in EXPERT_KERNELS:
        raise ValueError(f"Unknown expert kernel: {kernel}")
    if kernel != "torch_grouped_mm":
        if torch.device(device).type != "cuda" or torch.cuda.get_device_capability(device) != (12, 0):
            raise ValueError("triton_sm120 requires a validated SM120 CUDA device")
        from . import _triton_gemm  # noqa: F401


class _GroupedLinear(torch.autograd.Function):
    @staticmethod
    def forward(ctx, x, weight, offsets, forward_backend="triton_sm120"):
        from ._triton_gemm import linear_forward

        if (x.ndim != 2 or weight.ndim != 3 or offsets.ndim != 1
                or x.shape[1] != weight.shape[2] or offsets.numel() != weight.shape[0]
                or x.dtype != torch.bfloat16 or weight.dtype != x.dtype
                or offsets.dtype != torch.int32 or not x.is_cuda
                or weight.device != x.device or offsets.device != x.device
                or not offsets.is_contiguous() or weight.shape[0] == 0):
            raise ValueError("Expected CUDA BF16 X[T,K], W[E,N,K] and contiguous int32 offsets[E]")
        # Offsets are sorted cumulative counts generated by the router. Avoid a
        # CPU round-trip here; malformed external offsets are outside this API.
        ctx.save_for_backward(x if ctx.needs_input_grad[1] else None,
                              weight if ctx.needs_input_grad[0] else None, offsets)
        ctx.weight_shape = weight.shape
        if forward_backend == "cublas_sm120_forward":
            from ._cublas_forward import linear_forward as cublas_forward

            return cublas_forward(x, weight, offsets)
        if forward_backend == "triton_sm120_backward":
            from transformers.integrations.moe import _grouped_linear

            return _grouped_linear(x, weight, offsets)
        return linear_forward(x, weight, offsets)

    @staticmethod
    @once_differentiable
    def backward(ctx, dy):
        from ._triton_gemm import linear_forward, linear_weight_gradient

        x, weight, offsets = ctx.saved_tensors
        dx = linear_forward(dy, weight.transpose(1, 2), offsets) if ctx.needs_input_grad[0] else None
        dw = linear_weight_gradient(x, dy, offsets, ctx.weight_shape) if ctx.needs_input_grad[1] else None
        return dx, dw, None, None


def grouped_linear(x, weight, offsets, kernel="torch_grouped_mm"):
    if kernel in {"triton_sm120", "triton_sm120_backward", "cublas_sm120_forward"}:
        return _GroupedLinear.apply(x, weight, offsets, kernel)
    if kernel != "torch_grouped_mm":
        raise ValueError(f"Unknown expert kernel: {kernel}")
    from transformers.integrations.moe import _grouped_linear

    return _grouped_linear(x, weight, offsets)
